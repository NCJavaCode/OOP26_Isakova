// Інтерфейс Nameable - описує поведінку "мати назву класу".
// Інтерфейс містить тільки оголошення методів (без тіла),
// реалізацію пишуть класи, які імплементують інтерфейс
interface Nameable {
    // змінює назву класу
    void setClassName(String name);

    // повертає назву класу
    String getClassName();
}